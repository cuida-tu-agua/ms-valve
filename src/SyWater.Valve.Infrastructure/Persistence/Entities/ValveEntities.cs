using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace SyWater.Valve.Infrastructure.Persistence.Entities;

/// <summary>1:1 copy of valve.valve_states (created by ms-valve-db). Not the domain entity.</summary>
[Table("valve_states", Schema = "valve")]
public sealed class ValveStateEntity
{
    [Key, Column("id")] public Guid Id { get; set; }
    [Column("place_id")] public Guid PlaceId { get; set; }
    [Column("device_id")] public Guid DeviceId { get; set; }
    [Column("state")] public string State { get; set; } = "UNKNOWN";
    [Column("last_confirmed_at")] public DateTime? LastConfirmedAt { get; set; }
    [Column("created_at")] public DateTime CreatedAt { get; set; }
    [Column("updated_at")] public DateTime UpdatedAt { get; set; }
}

/// <summary>1:1 copy of valve.valve_commands.</summary>
[Table("valve_commands", Schema = "valve")]
public sealed class ValveCommandEntity
{
    /// <summary>Created by valve-service (the ESP32 sends it back): never generated by the database.</summary>
    [Key, Column("id"), DatabaseGenerated(DatabaseGeneratedOption.None)] public Guid Id { get; set; }
    [Column("place_id")] public Guid PlaceId { get; set; }
    [Column("device_id")] public Guid DeviceId { get; set; }
    [Column("action")] public string Action { get; set; } = "";
    [Column("origin")] public string Origin { get; set; } = "MANUAL";
    [Column("status")] public string Status { get; set; } = "SENT";
    [Column("requested_by")] public Guid? RequestedBy { get; set; }
    [Column("requested_by_name")] public string? RequestedByName { get; set; }
    [Column("confirmed_with_code")] public bool ConfirmedWithCode { get; set; }
    [Column("created_at")] public DateTime CreatedAt { get; set; }
    [Column("sent_at")] public DateTime? SentAt { get; set; }
    [Column("timeout_at")] public DateTime TimeoutAt { get; set; }
    [Column("acknowledged_at")] public DateTime? AcknowledgedAt { get; set; }
    [Column("failure_reason")] public string? FailureReason { get; set; }
}
